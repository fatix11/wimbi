# Database
# https://docs.djangoproject.com/en/6.1/ref/settings/#databases
#
# Deliberately no custom search_path here. An earlier version put
# analytics_mirror ahead of public — which meant Django's OWN migrated
# tables (auth, sessions, admin) landed inside analytics_mirror instead of
# public, since CREATE TABLE without a schema qualifier always targets the
# first schema on the search_path. A later `DROP SCHEMA analytics_mirror
# CASCADE` (done to reset the mirror's shape) silently wiped django_session
# and friends along with it. Fix: the analytics_mirror app's unmanaged
# models schema-qualify their own db_table directly (see
# analytics_mirror/models.py) — Django's own tables stay in the normal
# default `public` schema, completely unaffected by whatever happens to
# analytics_mirror.

